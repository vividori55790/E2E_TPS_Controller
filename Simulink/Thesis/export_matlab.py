"""
export_matlab.py -- T8 prep: MATLAB/Simulink deployment of a trained SmoothRegHDC without file I/O at run time.

Writes
  smooth_reghdc_params.m          function p = smooth_reghdc_params()  -- the weights as literals (17 significant
                                  digits, so MATLAB doubles reproduce the Python float64 model bit for bit up to
                                  summation order); usable inside a MATLAB Function block (code generation)
  out/smooth_reghdc_testvec.csv   P [W, signed], V2 [V], D1, D2 from the Python model (incl. clamp corners)
smooth_reghdc_infer.m / test_smooth_reghdc_infer.m are hand-written next to it.

    python -I -X utf8 Simulink/Thesis/export_matlab.py [--model out/model_smooth_reghdc_b3.json]
"""
import argparse
import csv
import json
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import controllers as ct  # noqa: E402

OUT = os.path.join(HERE, "out")


def mat(name, a):
    a = np.atleast_2d(np.asarray(a, float))
    rows = [" ".join(f"{x:.17g}" for x in r) for r in a]
    return f"p.{name} = [" + " ...\n    ".join(r + ";" for r in rows)[:-1] + "];"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", default=os.path.join(OUT, "model_smooth_reghdc_b3.json"))
    a = ap.parse_args()
    d = json.load(open(a.model, encoding="utf-8"))
    m = ct.SmoothRegHDC(D=d["D"], sigma=d["sigma"], tau=d["tau"], name=d["name"])
    m.W, m.b, m.M, m.c = (np.asarray(d[k], float) for k in ("W", "b", "M", "c"))
    src = os.path.relpath(a.model, HERE).replace("\\", "/")
    lines = [
        "function p = smooth_reghdc_params()",
        f"% smooth_reghdc_params -- GENERATED by export_matlab.py from {src} ({d['name']}). Do not edit.",
        "% Smooth RegHDC: x = [|P|/P_MAX, (V2-V2_LO)/(V2_HI-V2_LO)] clipped to [0,1]; h = sqrt(2)*cos(x*W + b);",
        "% y = h*M/sqrt(D) + c; Delta = min(tau*log(1+exp(y/tau)), 0.5-D_MIN); [D1 D2] = 0.5 - Delta.",
        "%#codegen",
        f"p.D = {d['D']};",
        f"p.tau = {d['tau']:.17g};",
        f"p.P_MAX = {ct.P_MAX:.17g};",
        f"p.V2_LO = {ct.V2_LO:.17g};",
        f"p.V2_HI = {ct.V2_HI:.17g};",
        f"p.D_MIN = {ct.D_MIN:.17g};",
        mat("W", m.W),            # 2 x D
        mat("b", m.b[None, :]),   # 1 x D
        mat("M", m.M),            # D x 2
        mat("c", m.c[None, :]),   # 1 x 2
        "end",
    ]
    path_m = os.path.join(HERE, "smooth_reghdc_params.m")
    open(path_m, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")

    rng = np.random.default_rng(77)
    P = np.concatenate([rng.uniform(-1300, 1300, 200), [0, 1200, -1200, 1500, -1500, 25, -25, 600]])
    V = np.concatenate([rng.uniform(80, 112, 200), [95, 84, 109.2, 95, 120, 70, 94.8, 100]])
    D1, D2 = m.predict(np.abs(P), V)
    path_t = os.path.join(OUT, "smooth_reghdc_testvec.csv")
    with open(path_t, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["P", "V2", "D1", "D2"])
        for row in zip(P, V, D1, D2):
            w.writerow([f"{x:.17g}" for x in row])
    print(f"wrote {path_m} ({os.path.getsize(path_m)} B) and {path_t} ({P.size} vectors); "
          f"D1 range {D1.min():.4f}-{D1.max():.4f}, D2 range {D2.min():.4f}-{D2.max():.4f}")


if __name__ == "__main__":
    main()
