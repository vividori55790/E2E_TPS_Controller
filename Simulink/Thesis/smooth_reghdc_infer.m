function [D1, D2] = smooth_reghdc_infer(P_ref, V2, V1)
% smooth_reghdc_infer -- proposed Smooth RegHDC controller (T8): (P*, V2[, V1]) -> (D1, D2). D0 is closed by the PI.
%
% Same computation as controllers.SmoothRegHDC.predict (Python, float64). By the bridge symmetry the optimal
% (D1, D2) depend on |P| only, so the sign of P_ref is dropped here; the sign of D0 comes from the PI loop.
% V1 (measured HV link, optional, default 380 V): physics-normalised inputs V2' = V2*380/V1, |P|' = |P|*(380/V1)^2
% (ideal-DAB scaling; v1_invariance.py: with V1 = 361-399 V the raw inputs are > 5 mA worse than SPS at 9.5 % of
% points, worst -302 mA; normalised 0 %, worst -2.4 mA).
% Weights: smooth_reghdc_params.m (generated by export_matlab.py; literals, no file I/O -> usable in a MATLAB
% Function block). Self-check: test_smooth_reghdc_infer.m against out/smooth_reghdc_testvec.csv.
% PWM convention (DAB_Controller_System.m): primary pulse D1*Ts from 0, secondary pulse D2*Ts from D0, 0.5 = SPS.
%#codegen
    persistent p
    if isempty(p)
        p = smooth_reghdc_params();
    end
    if nargin < 3
        V1 = 380;
    end
    s = 380 / max(V1, 1);
    u = min(max(abs(P_ref) * s^2 / p.P_MAX, 0), 1);
    v = min(max((V2 * s - p.V2_LO) / (p.V2_HI - p.V2_LO), 0), 1);
    h = sqrt(2) * cos([u, v] * p.W + p.b);          % 1 x D random-Fourier (HDC continuous) encoding
    y = h * p.M / sqrt(p.D) + p.c;                  % 1 x 2 linear read-out
    t = y / p.tau;                                  % softplus_tau, overflow-safe: tau*(max(t,0) + log1p(exp(-|t|)))
    sp = p.tau * (max(t, 0) + log1p(exp(-abs(t))));
    delta = min(sp, 0.5 - p.D_MIN);
    D1 = 0.5 - delta(1);
    D2 = 0.5 - delta(2);
end
