"""
c_compile_check.py -- T9 leftover: compile the exported MCU code (out/smooth_reghdc.c + .h + out/SmoothRegHDC_STM32.h) on this
PC and compare it with the Python emulation that every evaluation used (export_mcu.SmoothRegHDCFixed = the "int16" rows).

  python -I -X utf8 Simulink/Thesis/c_compile_check.py [--n 20000] [--lcc DIR] [--keep] [--no-write] [--mutate] [--mutate-v1]
  --mutate  self-test: the copies get one broken operation (>> 15 -> >> 14 in the cos interpolation); the exactness checks
            must then FAIL (test_c_compile_check.py). Implies --no-write (out/ is left alone).
  --mutate-v1  the same for smooth_reghdc_v1_equiv (one factor s dropped); the v1 checks must then FAIL.

The V1-normalised input (added 2026-10-31 after v1x adopted it, REPORT 8.1): smooth_reghdc_v1_equiv() then both paths, on random
(|P|, V2, V1 361-399 V) against the float64 model at the equivalent input, at V1 = 380 V bit for bit against the path without it,
and on the 30 cases of v1x_check.py against the duties that ran in Simulink.

Compiler: the LCC-win64 that ships with MATLAB (sys/lcc64). It runs without MATLAB and without a licence. It is an x86-64 PC
compiler, not the STM32 tool chain, so this checks the C semantics of the file (uint32 wrap-around = phase mod one turn,
>> of a negative int32, int64 accumulation, float32 libm), not ARM code generation.
Two builds of the same text:
  A  the delivered smooth_reghdc.c unchanged -> D1, D2 of both paths;
  B  a probe copy: one line inserted after the read-out stores acc0/acc1 and y (the MAC loop text is byte-identical)
     -> exact int64 accumulators and float32 bits of y, compared with the Python integer arithmetic.
Inputs are passed and outputs returned as float32 bit patterns (no decimal rounding in between).
Build files go to a temporary directory; only out/c_compile_check.{log,csv} are written. Exit code 1 if a check fails.
"""
