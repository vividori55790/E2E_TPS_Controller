def sha1(path):
    return hashlib.sha1(open(path, "rb").read()).hexdigest()[:12]


def parse_c_array(txt, name):
    m = re.search(re.escape(name) + r"\[[^=]*=\s*\{(.*?)\};", txt, flags=re.S)
    if not m:
        raise ValueError(f"{name} not found in the header")
    return np.array([int(t) for t in m.group(1).replace("\n", " ").split(",") if t.strip()], dtype=np.int64)


def run(cmd, cwd, log):
    p = subprocess.run(cmd, cwd=cwd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, errors="replace")
    out = (p.stdout or "").strip()
    log.append(f"  $ {' '.join(os.path.basename(c) if i == 0 else c for i, c in enumerate(cmd))}  -> rc {p.returncode}"
               + (("\n    " + out.replace("\n", "\n    ")) if out else ""))
    return p.returncode, out


def build(tmp, lcc, tag, probe, log, warn, mutant=None):
    """compile harness + model file in tmp/<tag> (no -O: LCC's optimiser emits invalid SSE assembly for the softplus line,
    a compiler bug; MATLAB's own lcc64 mex options do not use -O either); returns the exe path or None.
    warn[tag] = number of compiler warnings for the model file smooth_reghdc.c (the harness is not counted)."""
    d = os.path.join(tmp, tag)
    os.makedirs(d)
    for f in FILES:
        shutil.copy(os.path.join(OUT, f), d)
    if mutant:
        src = open(os.path.join(d, "smooth_reghdc.c"), encoding="utf-8").read()
        if src.count(mutant[0]) != 1:
            raise RuntimeError("mutation site not found exactly once")
        open(os.path.join(d, "smooth_reghdc.c"), "w", encoding="utf-8", newline="\n").write(src.replace(*mutant))
        log.append(f"MUTANT build {tag}: {mutant[0]} -> {mutant[1]}")
    if probe:
        src = open(os.path.join(d, "smooth_reghdc.c"), encoding="utf-8").read()
        if src.count(PROBE_ANCHOR) != 1:
            raise RuntimeError("probe anchor not found exactly once -- smooth_reghdc.c changed, update PROBE_ANCHOR")
        src = src.replace(PROBE_ANCHOR, PROBE_ANCHOR + PROBE_LINE)
        src = src.replace('#include "SmoothRegHDC_STM32.h"\n',
                          '#include "SmoothRegHDC_STM32.h"\nlong long g_acc[2];\nfloat g_y[2];\n', 1)
        open(os.path.join(d, "smooth_reghdc.c"), "w", encoding="utf-8", newline="\n").write(src)
    open(os.path.join(d, "main.c"), "w", encoding="utf-8", newline="\n").write(HARNESS)
    cc, ln = os.path.join(lcc, "bin", "lcc64.exe"), os.path.join(lcc, "bin", "lcclnk64.exe")
    flags = ["-noregistrylookup", "-I" + os.path.join(lcc, "include64"), "-I" + d] + (["-DPROBE"] if probe else [])
    log.append(f"build {tag} ({'probe copy' if probe else 'delivered file unchanged'}):")
    for s in ("smooth_reghdc", "main"):
        rc, out = run([cc] + flags + ["-A", "-c", os.path.join(d, s + ".c"), "-Fo" + os.path.join(d, s + ".obj")], d, log)
        if s == "smooth_reghdc":
            warn[tag] = sum(1 for ln in out.splitlines() if ln.startswith("Warning"))
        if rc != 0:
            return None
    exe = os.path.join(d, "check.exe")
    rc, _ = run([ln, "-subsystem", "console", "-L" + os.path.join(lcc, "lib64"), os.path.join(d, "main.obj"),
                 os.path.join(d, "smooth_reghdc.obj"), "-o", exe], d, log)
    return exe if rc == 0 and os.path.exists(exe) else None


def execute(exe, inp, tag, log, extra=()):
    outp = os.path.join(os.path.dirname(exe), f"out_{tag}.txt")
    rc, txt = run([exe, inp, outp] + list(extra), os.path.dirname(exe), log)
    if rc != 0:
        return None
    rows = [ln.split() for ln in open(outp, encoding="ascii").read().splitlines() if ln.strip()]
    return rows


def f32(hexcol):
    return np.array([int(h, 16) for h in hexcol], dtype=np.uint32).view(np.float32)


def s64(hexcol):
    v = np.array([int(h, 16) for h in hexcol], dtype=object)
    return np.array([int(x) - (1 << 64) if int(x) >= (1 << 63) else int(x) for x in v], dtype=np.int64)


def acc_emul(fx, uq, vq):
    """integer part of SmoothRegHDCFixed.raw_q (same operations), returned before the float conversion"""
    fb = fx.k + 15
    ph = (uq[:, None] * fx.WQ[0][None] + vq[:, None] * fx.WQ[1][None] + (fx.BQ << (fx.k - 1))[None]) & 0xFFFFFFFF
    frac = ph & ((1 << fb) - 1)
    sh = fb - 10
    idx = frac >> sh
    fr = (frac >> (sh - 15)) & 0x7FFF if sh >= 15 else (frac << (15 - sh)) & 0x7FFF
    t0, t1 = fx.COS[idx], fx.COS[idx + 1]
    c = t0 + (((t1 - t0) * fr) >> 15)
    return c @ fx.MQ


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=20000)
    ap.add_argument("--lcc", default=LCC_DEFAULT)
    ap.add_argument("--keep", action="store_true", help="keep the temporary build directory")
    ap.add_argument("--no-write", action="store_true", help="print only, do not write out/c_compile_check.*")
    ap.add_argument("--mutate", action="store_true", help="self-test with one broken operation (implies --no-write)")
    ap.add_argument("--mutate-v1", action="store_true", help="self-test with one broken operation in the V1 function (implies --no-write)")
    a = ap.parse_args()
    write = not (a.no_write or a.mutate or a.mutate_v1)
    mutant = MUTANT if a.mutate else MUTANT_V1 if a.mutate_v1 else None
    log, rows_csv, fails = [], [], []

    def metric(name, value, ok=None, note=""):
        rows_csv.append((name, value, "" if ok is None else ("PASS" if ok else "FAIL"), note))
        if ok is not None and not ok:           # not `ok is False`: most checks hand in a numpy bool
            fails.append(name)

    hdr = open(os.path.join(OUT, "SmoothRegHDC_STM32.h"), encoding="utf-8").read()
    m = re.search(r"generated by \S+ from (\S+?)\.\s", hdr)
    model_json = os.path.join(OUT, m.group(1) if m else "model_smooth_reghdc_b3.json")
    base = ct.SmoothRegHDC.from_json(model_json)
    fx = em.SmoothRegHDCFixed(base)
    log.append(f"model {os.path.basename(model_json)} (from the header's first line); files compiled: "
               + ", ".join(f"{f} sha1 {sha1(os.path.join(OUT, f))}" for f in FILES))
    # the header must hold exactly the parameter set the emulation uses
    same = (np.array_equal(parse_c_array(hdr, "SRHDC_WQ"), fx.WQ.ravel())
            and np.array_equal(parse_c_array(hdr, "SRHDC_BQ"), fx.BQ.ravel())
            and np.array_equal(parse_c_array(hdr, "SRHDC_MQ"), fx.MQ.ravel())
            and np.array_equal(parse_c_array(hdr, "SRHDC_COS_Q15"), fx.COS.ravel())
            and f"SRHDC_WQ_SHIFT {fx.k}" in hdr and f"SRHDC_MQ_SHIFT {fx.m}" in hdr)
    log.append(f"header int16 tables (WQ, BQ, MQ, COS_Q15, shifts) == SmoothRegHDCFixed of that model: {same}")
    metric("header_tables_equal_emulation", int(same), same)

    # inputs: random + edges + the MATLAB test vectors, as float32
    rng = np.random.default_rng(2026)
    P = [rng.uniform(0, ct.P_MAX, a.n)]
    V = [rng.uniform(ct.V2_LO, ct.V2_HI, a.n)]
    eP, eV = np.meshgrid([0.0, 1e-3, 0.5, 100.0, 600.0, 1199.9, 1200.0, 1500.0, -10.0],
                         [83.0, 84.0, 95.0, 109.2, 115.0])
    P.append(eP.ravel())
    V.append(eV.ravel())
    tv = np.genfromtxt(os.path.join(OUT, "smooth_reghdc_testvec.csv"), delimiter=",", names=True)
    P.append(np.abs(tv["P"]))
    V.append(tv["V2"])
    P32, V32 = np.concatenate(P).astype(np.float32), np.concatenate(V).astype(np.float32)
    n_r, n_e, n_t = a.n, eP.size, len(tv)
    N = P32.size

    # V1-normalised input: random V1, then V1 = 380 V on the first random points above, then the 30 cases of v1x_check.py
    import v1x_check as vx
    n_v = min(a.n, 5000)
    vcases = vx.cases()
    PV = np.concatenate([rng.uniform(0, ct.P_MAX, n_v), P[0][:n_v], [c[3] for c in vcases]]).astype(np.float32)
    VV = np.concatenate([rng.uniform(ct.V2_LO, ct.V2_HI, n_v), V[0][:n_v], [c[2] for c in vcases]]).astype(np.float32)
    V1V = np.concatenate([rng.uniform(361.0, 399.0, n_v), np.full(n_v, 380.0), [vx.rc.params(c[1])["V1"] for c in vcases]]).astype(np.float32)

    tmp = tempfile.mkdtemp(prefix="srhdc_c_")
    try:
        inp = os.path.join(tmp, "in.txt")
        with open(inp, "w", encoding="ascii", newline="\n") as f:
            for pb, vb in zip(P32.view(np.uint32), V32.view(np.uint32)):
                f.write(f"{pb:08x} {vb:08x}\n")
        inv = os.path.join(tmp, "in_v1.txt")
        with open(inv, "w", encoding="ascii", newline="\n") as f:
            for pb, vb, v1b in zip(PV.view(np.uint32), VV.view(np.uint32), V1V.view(np.uint32)):
                f.write(f"{pb:08x} {vb:08x} {v1b:08x}\n")
        warn = {}
        exeA = build(tmp, a.lcc, "A", False, log, warn, mutant)
        exeB = build(tmp, a.lcc, "B", True, log, warn, mutant)
        metric("compile_link_delivered_file", int(exeA is not None), exeA is not None,
               "LCC-win64 with -A (all warnings); harness supplies log1pf, missing from LCC's libc64")
        metric("compiler_warnings_model_file", warn.get("A", -1), warn.get("A", -1) == 0, "smooth_reghdc.c with -A")
        if exeA is None or exeB is None:
            raise SystemExit(finish(log, rows_csv, fails + ["build"], write=write))
        outv = os.path.join(tmp, "out_v1.txt")
        rA = execute(exeA, inp, "A", log, (inv, outv))
        rB = execute(exeB, inp, "B", log)
        if rA is None or rB is None or len(rA) != N or len(rB) != N:
            log.append(f"run failed or wrong row count (A {None if rA is None else len(rA)}, "
                       f"B {None if rB is None else len(rB)}, expected {N})")
            raise SystemExit(finish(log, rows_csv, fails + ["run"], write=write))
        cA, cB = list(zip(*rA)), list(zip(*rB))
        uq, vq = np.array(cA[0], dtype=np.int64), np.array(cA[1], dtype=np.int64)
        d1q, d2q, d1f, d2f = (f32(cA[i]).astype(np.float64) for i in (2, 3, 4, 5))
        accC = np.stack([s64(cB[4]), s64(cB[5])], axis=1)
        yC = np.stack([f32(cB[6]), f32(cB[7])], axis=1)
        same_AB = (list(cA[0]) == list(cB[0]) and list(cA[1]) == list(cB[1]) and list(cA[2]) == list(cB[2])
                   and list(cA[3]) == list(cB[3]))
        metric("probe_build_same_D_as_delivered", int(same_AB), same_AB, "the inserted line changes nothing")

        # (1) integer path: exact int64 accumulators, then float32 y bits vs the evaluation emulator
        accP = acc_emul(fx, uq, vq)
        n_acc = int(np.all(accP == accC, axis=1).sum())
        metric("int64_accumulators_identical", f"{n_acc}/{N}", n_acc == N, "C probe vs numpy int64, C's own Q15 inputs")
        yP = fx.raw_q(uq, vq)
        n_y = int(np.all(yP.view(np.uint32) == yC.view(np.uint32), axis=1).sum())
        metric("y_float32_bits_identical", f"{n_y}/{N}", n_y == N, "C probe vs SmoothRegHDCFixed.raw_q")

        # (2) Q15 input conversion: C lrintf on float32 vs Python round on float64
        x = ct.norm_inputs(P32.astype(np.float64), V32.astype(np.float64)).reshape(-1, 2)
        uqP, vqP = np.round(x[:, 0] * 32767).astype(np.int64), np.round(x[:, 1] * 32767).astype(np.int64)
        du, dv = np.abs(uq - uqP), np.abs(vq - vqP)
        n_in = int(((du > 0) | (dv > 0)).sum())
        metric("q15_input_diff_points", f"{n_in}/{N}", int(max(du.max(), dv.max())) <= 1,
               f"max {int(max(du.max(), dv.max()))} LSB (1 LSB = {ct.P_MAX / 32767:.4f} W / "
               f"{(ct.V2_HI - ct.V2_LO) / 32767 * 1e3:.3f} mV)")

        # (3) D outputs
        P64, V64 = P32.astype(np.float64), V32.astype(np.float64)
        e1, e2 = fx.predict(P64, V64)                       # what evaluate.py reports as the int16 controller
        r1, r2 = base.predict(P64, V64)                     # float64 model
        f1, f2 = em.float32_predict(base, P64, V64)         # numpy float32 path
        dq_emul = max(np.abs(d1q - e1).max(), np.abs(d2q - e2).max())
        sel = (du == 0) & (dv == 0)
        dq_emul_same_in = max(np.abs(d1q - e1)[sel].max(), np.abs(d2q - e2)[sel].max())
        metric("max_dD_C_q15_vs_emulation", f"{dq_emul:.3e}", dq_emul <= 1e-4,
               f"same Q15 inputs: {dq_emul_same_in:.3e} (float32 vs float64 softplus)")
        dq_model = max(np.abs(d1q - r1).max(), np.abs(d2q - r2).max())
        rq_model = float(np.sqrt(np.mean(np.concatenate([(d1q - r1) ** 2, (d2q - r2) ** 2]))))
        metric("max_dD_C_q15_vs_float64_model", f"{dq_model:.3e}", dq_model <= 5e-4, f"RMS {rq_model:.2e} (export log 2.65e-4)")
        df_model = max(np.abs(d1f - r1).max(), np.abs(d2f - r2).max())
        metric("max_dD_C_f32_vs_float64_model", f"{df_model:.3e}", df_model <= 1e-5, "export log 5.6e-7")
        df_np = max(np.abs(d1f - f1).max(), np.abs(d2f - f2).max())
        metric("max_dD_C_f32_vs_numpy_float32", f"{df_np:.3e}", df_np <= 1e-5)
        it = slice(n_r + n_e, N)
        dt_q = max(np.abs(d1q[it] - tv["D1"]).max(), np.abs(d2q[it] - tv["D2"]).max())
        dt_f = max(np.abs(d1f[it] - tv["D1"]).max(), np.abs(d2f[it] - tv["D2"]).max())
        metric("max_dD_testvec_q15_f32", f"{dt_q:.3e} / {dt_f:.3e}", dt_f <= 1e-5,
               f"{n_t} vectors of smooth_reghdc_testvec.csv (|P|), q15 bound by quantisation")
        ok_range = bool(np.all((d1q >= ct.D_MIN - 1e-7) & (d1q <= 0.5) & (d2q >= ct.D_MIN - 1e-7) & (d2q <= 0.5)
                            & (d1f >= ct.D_MIN - 1e-7) & (d1f <= 0.5) & (d2f >= ct.D_MIN - 1e-7) & (d2f <= 0.5)))
        metric("all_outputs_in_[D_MIN,0.5]", int(ok_range), ok_range)

        ie = slice(n_r, n_r + n_e)
        log.append("\nedge inputs (C q15 / C f32 / float64 model; P < 0 and out-of-range V2 are clipped like the model):")
        log.append("     |P| [W]   V2 [V]   u_q15  v_q15   D1 q15   D2 q15   D1 f32   D2 f32   D1 mdl   D2 mdl")
        for k in range(ie.start, ie.stop):
            log.append(f"  {P32[k]:10.3f} {V32[k]:8.2f} {uq[k]:7d} {vq[k]:6d}  {d1q[k]:.5f}  {d2q[k]:.5f}  {d1f[k]:.5f}"
                       f"  {d2f[k]:.5f}  {r1[k]:.5f}  {r2[k]:.5f}")
        de = max(np.abs(d1q[ie] - r1[ie]).max(), np.abs(d2q[ie] - r2[ie]).max(), np.abs(d1f[ie] - r1[ie]).max(),
                 np.abs(d2f[ie] - r2[ie]).max())
        metric("max_dD_edge_inputs", f"{de:.3e}", de <= 5e-4)

        # (4) V1-normalised input
        rV = list(zip(*[ln.split() for ln in open(outv, encoding="ascii").read().splitlines() if ln.strip()]))
        pe, ve, dv1q, dv2q, dv1f, dv2f = (f32(c) for c in rV)
        s64v = 380.0 / V1V.astype(np.float64)
        Pe, Ve = PV.astype(np.float64) * s64v ** 2, VV.astype(np.float64) * s64v
        rel = max(np.abs(pe / Pe - 1).max(), np.abs(ve / Ve - 1).max())
        metric("v1_equiv_inputs_max_relative_error", f"{rel:.2e}", rel <= 1e-6, "C float32 against 380/V1 in float64")
        m1, m2 = base.predict(Pe, Ve)
        ir = slice(0, n_v)
        dvf = max(np.abs(dv1f - m1)[ir].max(), np.abs(dv2f - m2)[ir].max())
        metric("v1_max_dD_C_f32_vs_float64_model", f"{dvf:.3e}", dvf <= 1e-5, f"{n_v} random points, V1 361-399 V")
        dvq = max(np.abs(dv1q - m1)[ir].max(), np.abs(dv2q - m2)[ir].max())
        metric("v1_max_dD_C_q15_vs_float64_model", f"{dvq:.3e}", dvq <= 5e-4, f"{n_v} random points, V1 361-399 V")
        same = 0
        for k in range(n_v):
            same += rV[2][n_v + k] == cA[2][k] and rV[3][n_v + k] == cA[3][k] and rV[4][n_v + k] == cA[4][k] and rV[5][n_v + k] == cA[5][k]
        metric("v1_380V_bits_identical_to_plain_path", f"{same}/{n_v}", same == n_v, "both paths, V1 = 380 V against no normalisation")
        mb = ct.SmoothRegHDC.from_json(os.path.join(OUT, "model_smooth_reghdc_b3.json"))
        ran = np.array([vx.controllers(mb, c[1], c[2], c[3])[vx.MK] for c in vcases])
        iv = slice(2 * n_v, 2 * n_v + len(vcases))
        dvx = max(np.abs(dv1f[iv] - ran[:, 0]).max(), np.abs(dv2f[iv] - ran[:, 1]).max())
        metric("v1x_cases_max_dD_vs_simulink_duties", f"{dvx:.3e}", dvx <= vx.rm.SAME + 1e-5,
               f"{len(vcases)} cases; runs within r13_map.SAME = {vx.rm.SAME} of SPS or M-B shared those runs")
    finally:
        if a.keep:
            log.append(f"\nbuild directory kept: {tmp}")
        else:
            shutil.rmtree(tmp, ignore_errors=True)
    return finish(log, rows_csv, fails, N, n_r, n_e, n_t, write=write)


def finish(log, rows_csv, fails, N=0, n_r=0, n_e=0, n_t=0, write=True):
    head = [f"c_compile_check: {N} points = {n_r} random (seed 2026, |P| 0-1200 W, V2 84-109.2 V) + {n_e} edge + {n_t} "
            "MATLAB test vectors; compiler LCC-win64 (MATLAB sys/lcc64), x86-64 PC -- C semantics, not ARM code"]
    body = [f"  {n:<36s} {v!s:<22s} {s:<5s} {note}" for n, v, s, note in rows_csv]
    verdict = "ALL PASS" if not fails else "FAIL: " + ", ".join(fails)
    txt = "\n".join(head + [""] + log + ["", "checks:"] + body + ["", verdict]) + "\n"
    print(txt)
    if not write:
        return 0 if not fails else 1
    open(os.path.join(OUT, "c_compile_check.log"), "w", encoding="utf-8").write(txt)
    with open(os.path.join(OUT, "c_compile_check.csv"), "w", encoding="utf-8", newline="\n") as f:
        f.write("check,value,result,note\n")
        for n, v, s, note in rows_csv:
            f.write(f"{n},{v},{s},\"{note}\"\n")
    return 0 if not fails else 1


